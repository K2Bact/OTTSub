  // UI locale normalization only. Subtitle identities are owned by track-languages.
  function resolveLanguage(lang) {
    if (typeof lang !== 'string') return null;
    const lower = lang.trim().replaceAll('_', '-').toLowerCase();
    if (/^zh-(?:tw|hant)(?:-|$)/.test(lower)) return 'zh-TW';
    if (/^pt-pt(?:-|$)/.test(lower)) return 'pt-PT';
    const base = lower.split('-')[0];
    return Object.prototype.hasOwnProperty.call(TRANSLATIONS, base) ? base : null;
  }

  function detectBrowserLanguage() {
    try {
      const api = typeof chrome !== 'undefined' ? chrome : window.chrome;
      const uiLanguage = resolveLanguage(api?.i18n?.getUILanguage?.());
      if (uiLanguage) return uiLanguage;
    } catch (_) {}
    try {
      const langs = (typeof navigator !== 'undefined' && Array.isArray(navigator.languages) && navigator.languages.length > 0)
        ? navigator.languages
        : [(typeof navigator !== 'undefined' ? (navigator.language || navigator.userLanguage) : 'en') || 'en'];
      for (const l of langs) {
        const resolved = resolveLanguage(l);
        if (resolved) return resolved;
      }
    } catch (_) {}
    return 'en';
  }

  let currentLanguage = detectBrowserLanguage();

  const I18n = {
    detectBrowserLanguage,
    resolveLanguage,

    getLanguage() {
      return currentLanguage;
    },

    setLanguage(lang) {
      const normalized = resolveLanguage(lang);
      if (normalized) currentLanguage = normalized;
      return currentLanguage;
    },

    /**
     * Translate a key with optional dynamic parameter interpolation.
     * Hardened against prototype pollution, missing keys, and invalid parameters.
     */
    t(key, params = {}, lang = null) {
      if (typeof key !== 'string' || !key) return '';

      const targetLang = (typeof lang === 'string' && lang) ? (resolveLanguage(lang) || 'en') : currentLanguage;
      const dict = TRANSLATIONS[targetLang] || TRANSLATIONS.en;

      let text = (Object.prototype.hasOwnProperty.call(dict, key) && typeof dict[key] === 'string')
        ? dict[key]
        : ((Object.prototype.hasOwnProperty.call(TRANSLATIONS.en, key) && typeof TRANSLATIONS.en[key] === 'string')
            ? TRANSLATIONS.en[key]
            : key);

      if (params && typeof params === 'object') {
        for (const pKey of Object.keys(params)) {
          if (pKey === '__proto__' || pKey === 'constructor' || pKey === 'prototype') continue;
          const val = params[pKey] != null ? String(params[pKey]) : '';
          text = text.replaceAll(`{${pKey}}`, val);
        }
      }

      if (key.startsWith('shortcut_') && text.startsWith('Alt +')
        && window.OTTSubPlatform?.getOS() === 'mac') {
        text = 'Option' + text.slice(3);
      }
      return text;
    },

    /**
     * Batch update all elements in root with data-i18n attributes
     */
    updateDOM(root = document, lang = null) {
      if (!root || typeof root.querySelectorAll !== 'function') return;
      const targetLang = (typeof lang === 'string' && lang) ? (resolveLanguage(lang) || 'en') : currentLanguage;

      const elements = root.querySelectorAll('[data-i18n]');
      if (elements) {
        elements.forEach(el => {
          const key = el.getAttribute('data-i18n');
          if (key) {
            el.textContent = this.t(key, {}, targetLang);
          }
        });
      }

      // Update secondary language option labels if present
      const langOptions = root.querySelectorAll('option[data-i18n-option]');
      if (langOptions) {
        langOptions.forEach(opt => {
          const key = opt.getAttribute('data-i18n-option');
          if (key) {
            opt.textContent = this.t(key, {}, targetLang);
          }
        });
      }

      // Update title attributes for tooltips
      const titleElements = root.querySelectorAll('[data-i18n-title]');
      if (titleElements) {
        titleElements.forEach(el => {
          const key = el.getAttribute('data-i18n-title');
          if (key) {
            el.setAttribute('title', this.t(key, {}, targetLang));
          }
        });
      }

      // Update aria-label attributes for accessibility
      const ariaLabelElements = root.querySelectorAll('[data-i18n-aria-label]');
      if (ariaLabelElements) {
        ariaLabelElements.forEach(el => {
          const key = el.getAttribute('data-i18n-aria-label');
          if (key) {
            el.setAttribute('aria-label', this.t(key, {}, targetLang));
          }
        });
      }
    }
  };

  window.OTTSubI18n = I18n;
